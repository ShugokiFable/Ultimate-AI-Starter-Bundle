<#
.SYNOPSIS
  Write correct .cbmignore files so codebase-memory-mcp indexes source, not assets.

.DESCRIPTION
  Indexing a Skyrim mod tree without scope control produces graphs of 100,000+ nodes
  made almost entirely of vendored headers, duplicated version snapshots and binary
  assets. This script writes a per-project .cbmignore that removes all four bloat
  sources, and resolves versioned workspaces against CURRENT.txt.

  Case sensitivity: .cbmignore matching IS case-sensitive, and Skyrim capitalizes
  Meshes/Textures/Sound. Every asset rule is emitted in both cases on purpose.

  Source-carrier exception: where a project's active version is a packaged release
  with no source, the source often lives only in an older snapshot. This script
  detects that and keeps that snapshot too, rather than silently dropping the only
  copy of the code.

  Safe by default: reports what it would do. Pass -Apply to write.
  It only ever writes .cbmignore files; it never deletes or indexes anything.

.PARAMETER Path
  A project root, or a workspace root when used with -Recurse.

.PARAMETER Recurse
  Treat -Path as a workspace and process each immediate child directory as a project.

.PARAMETER Apply
  Actually write the .cbmignore files. Without this the script only reports.

.PARAMETER ExcludeName
  Child directory names to skip in -Recurse mode (archives, staging, templates).

.EXAMPLE
  .\Setup-CodebaseMemory-Index.ps1 -Path 'Z:\Work\MyMod'

.EXAMPLE
  .\Setup-CodebaseMemory-Index.ps1 -Path 'Z:\Work\AiWorkspace' -Recurse -Apply

.NOTES
  After running, index with:
    index_repository(repo_path=<project root>, mode=moderate, name=<stable-slug>)
  Then sanity-check node count against file count, and confirm languages with
  get_architecture(aspects=["languages"]).
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Path,
    [switch]$Recurse,
    [switch]$Apply,
    [string[]]$ExcludeName = @('zOlder', '_stage', '_inspect', '.pnpm-store', '_AI-SHARED-MEMORY')
)

$ErrorActionPreference = 'Stop'

# Marker delimits the generated stale-snapshot block so re-runs are idempotent.
$marker = '# --- stale version snapshots (generated; re-run the script to refresh) ---'

$baseIgnore = @'
