# Generated by TOOLS/Setup-CodebaseMemory-Index.ps1
#
# MATCHING IS CASE-SENSITIVE: `meshes/` does NOT match `Meshes/`.
# Asset rules are listed in both cases on purpose - do not tidy them away.

